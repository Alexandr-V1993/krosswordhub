// Словарь и генератор кроссвордов.
// Каждый раз сетка собирается заново из случайных слов словаря.
// «Кроссворд дня» строится от даты, поэтому в один день он одинаковый для всех.

export type CategoryId = "nature" | "travel" | "culture" | "food" | "science" | "everyday" | "sport";
export type Level = "Лёгкий" | "Средний" | "Сложный";
export type Direction = "across" | "down";

export type PWord = {
  number: number;
  direction: Direction;
  clue: string;
  answer: string;
  hint: string;
  cells: [number, number][];
};

export type Puzzle = {
  id: string;
  title: string;
  description: string;
  category: CategoryId | "all";
  level: Level;
  /** Номер в каталоге темы (1…PER_THEME); у случайных и «дня» его нет */
  number?: number;
  rows: number;
  cols: number;
  /** Буква решения, а для чёрной клетки — пустая строка */
  grid: string[][];
  /** Номера в начале слов: ключ "r-c" */
  numbers: Record<string, number>;
  words: PWord[];
};

export const levels: Level[] = ["Лёгкий", "Средний", "Сложный"];

/** Сколько готовых нумерованных кроссвордов в каждой теме */
export const PER_THEME = 60;
/** №1–20 лёгкие, №21–40 средние, №41–60 сложные */
export const levelForNumber = (n: number): Level => (n <= 20 ? "Лёгкий" : n <= 40 ? "Средний" : "Сложный");

