export const numberedId = (cat: ThemeId, n: number) => `${cat}-${n}`;

/** Кроссворд №n темы: сетка всегда одна и та же для одного номера */
export function numberedPuzzle(cat: ThemeId, n: number): Puzzle {
  const num = Math.min(PER_THEME, Math.max(1, Math.floor(n)));
  return generatePuzzle({
    category: cat,
    level: levelForNumber(num),
    seed: hashString(`${cat}#${num}`),
    id: numberedId(cat, num),
    number: num,
    title: `${getCategoryName(cat)} · № ${String(num).padStart(2, "0")}`,
  });
}

/** Восстанавливает кроссворд по id (из списка решённых). null — если id незнакомый. */
export function puzzleFromId(id: string): Puzzle | null {
  let m = /^daily-(\d{4}-\d{2}-\d{2})$/.exec(id);
  if (m) return dailyPuzzle(m[1]);
  m = /^(all|nature|travel|culture|food|science|everyday|sport)-(\d{1,3})$/.exec(id);
  if (m) {
    const n = Number(m[2]);
    return n >= 1 && n <= PER_THEME ? numberedPuzzle(m[1] as ThemeId, n) : null;
  }
  m = /^r-(all|nature|travel|culture|food|science|everyday|sport)-([0-2])-(\d+)$/.exec(id);
  if (m) return generatePuzzle({ category: m[1] as ThemeId, level: levels[Number(m[2])], seed: Number(m[3]) });
  return null;
}

/**
 * Следующий кроссворд «по этой теме»:
 * — нумерованный → следующий по номеру, пропуская уже решённые;
 * — кроссворд дня → первый нерешённый из «вперемешку»;
 * — случайный → новая случайная сетка той же темы и сложности.
 */
export function nextPuzzle(p: Puzzle, solved: Set<string>): Puzzle {
  if (p.number !== undefined) {
    for (let step = 1; step <= PER_THEME; step++) {
      const n = ((p.number - 1 + step) % PER_THEME) + 1;
      if (!solved.has(numberedId(p.category, n))) return numberedPuzzle(p.category, n);
    }
    return numberedPuzzle(p.category, (p.number % PER_THEME) + 1);
  }
  if (p.id.startsWith("daily-")) {
    for (let n = 1; n <= PER_THEME; n++) if (!solved.has(numberedId("all", n))) return numberedPuzzle("all", n);
  }
  return generatePuzzle({ category: p.category, level: p.level, seed: randomSeed() });
}

