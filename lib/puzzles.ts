type Bank = { a: string; clue: string; cat: CategoryId };

const bank: Bank[] = (() => {
  const seen = new Set<string>();
  const out: Bank[] = [];
  (Object.keys(RAW) as CategoryId[]).forEach(cat => {
    RAW[cat].split("\n").forEach(line => {
      const [ans, clue] = line.split("|");
      const a = (ans || "").trim().toUpperCase().replace(/Ё/g, "Е");
      if (!a || !clue || !/^[А-Я]+$/.test(a) || seen.has(a)) return;
      seen.add(a);
      out.push({ a, clue: clue.trim(), cat });
    });
  });
  return out;
})();

export const WORD_COUNT = bank.length;

// ---------- Случайные числа ----------
function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
export function hashString(s: string) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
export const randomSeed = () => Math.floor(Math.random() * 4294967295) + 1;

function shuffle<T>(arr: T[], rnd: () => number) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

