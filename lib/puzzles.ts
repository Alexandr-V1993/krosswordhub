export const THEME_IDS: ThemeId[] = categories.map(c => c.id);
export const isThemeId = (v: string): v is ThemeId => (THEME_IDS as string[]).includes(v);

/** Быстрая проверка id кроссворда без генерации сетки (для маршрутов) */
export function isPuzzleId(id: string): boolean {
  let m = /^daily-(\d{4})-(\d{2})-(\d{2})$/.exec(id);
  if (m) return Number(m[2]) >= 1 && Number(m[2]) <= 12 && Number(m[3]) >= 1 && Number(m[3]) <= 31;
  m = /^([a-z]+)-(\d{1,3})$/.exec(id);
  if (m) return isThemeId(m[1]) && Number(m[2]) >= 1 && Number(m[2]) <= PER_THEME;
  m = /^r-([a-z]+)-([0-2])-(\d{1,10})$/.exec(id);
  return !!m && isThemeId(m[1]);
}

/** id нового случайного кроссворда: его можно открыть по ссылке /crossword/<id> */
export const randomId = (category: ThemeId, level: Level) => `r-${category}-${levels.indexOf(level)}-${randomSeed()}`;

/** Все id нумерованных кроссвордов (для статической генерации и sitemap) */
export function allNumberedIds(): string[] {
  const out: string[] = [];
  for (const c of categories) for (let n = 1; n <= PER_THEME; n++) out.push(numberedId(c.id, n));
  return out;
}
