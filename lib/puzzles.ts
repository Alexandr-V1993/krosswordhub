const LEVEL_CFG: Record<Level, { size: number; target: number; min: number; max: number }> = {
  "Лёгкий": { size: 12, target: 9, min: 3, max: 6 },
  "Средний": { size: 14, target: 14, min: 3, max: 8 },
  "Сложный": { size: 16, target: 20, min: 3, max: 10 },
};

type Placed = { a: string; clue: string; row: number; col: number; dir: Direction };

function build(rnd: () => number, pool: Bank[], cfg: { size: number; target: number; min: number; max: number }) {
  const { size, target } = cfg;
  const grid: string[][] = Array.from({ length: size }, () => Array(size).fill(""));
  const used: number[][] = Array.from({ length: size }, () => Array(size).fill(0));
  const placed: Placed[] = [];
  const taken = new Set<string>();
  let crossTotal = 0;
  const inb = (r: number, c: number) => r >= 0 && c >= 0 && r < size && c < size;

  const check = (w: string, row: number, col: number, dir: Direction, first: boolean) => {
    const dr = dir === "down" ? 1 : 0;
    const dc = dir === "across" ? 1 : 0;
    const len = w.length;
    const er = row + dr * (len - 1);
    const ec = col + dc * (len - 1);
    if (!inb(row, col) || !inb(er, ec)) return -1;
    if (inb(row - dr, col - dc) && grid[row - dr][col - dc]) return -1;
    if (inb(er + dr, ec + dc) && grid[er + dr][ec + dc]) return -1;
    const bit = dir === "across" ? 1 : 2;
    let cross = 0;
    for (let i = 0; i < len; i++) {
      const r = row + dr * i;
      const c = col + dc * i;
      const cur = grid[r][c];
      if (cur) {
        if (cur !== w[i]) return -1;
        if (used[r][c] & bit) return -1;
        cross++;
      } else {
        if (inb(r + dc, c + dr) && grid[r + dc][c + dr]) return -1;
        if (inb(r - dc, c - dr) && grid[r - dc][c - dr]) return -1;
      }
    }
    if (!first && cross === 0) return -1;
    return cross;
  };

  const put = (b: Bank, row: number, col: number, dir: Direction) => {
    const dr = dir === "down" ? 1 : 0;
    const dc = dir === "across" ? 1 : 0;
    const bit = dir === "across" ? 1 : 2;
    for (let i = 0; i < b.a.length; i++) {
      grid[row + dr * i][col + dc * i] = b.a[i];
      used[row + dr * i][col + dc * i] |= bit;
    }
    placed.push({ a: b.a, clue: b.clue, row, col, dir });
    taken.add(b.a);
  };

  const cand = shuffle(pool.filter(b => b.a.length >= cfg.min && b.a.length <= cfg.max), rnd);
  if (!cand.length) return { grid, placed, crossTotal };

  // первое слово — одно из самых длинных среди первых кандидатов
  const head = cand.slice(0, 12).sort((x, y) => y.a.length - x.a.length)[0];
  const startRow = Math.floor(size / 2) + Math.floor(rnd() * 3) - 1;
  const startCol = Math.max(0, Math.floor((size - head.a.length) / 2));
  put(head, Math.min(size - 1, startRow), startCol, "across");

  for (let pass = 0; pass < 4 && placed.length < target; pass++) {
    for (const w of cand) {
      if (placed.length >= target) break;
      if (taken.has(w.a)) continue;
      const opts: { row: number; col: number; dir: Direction; cross: number }[] = [];
      for (let r = 0; r < size; r++) {
        for (let c = 0; c < size; c++) {
          const ch = grid[r][c];
          if (!ch) continue;
          for (let i = 0; i < w.a.length; i++) {
            if (w.a[i] !== ch) continue;
            (["across", "down"] as Direction[]).forEach(dir => {
              const row = dir === "across" ? r : r - i;
              const col = dir === "across" ? c - i : c;
              const cross = check(w.a, row, col, dir, false);
              if (cross > 0) opts.push({ row, col, dir, cross });
            });
          }
        }
      }
      if (!opts.length) continue;
      const best = Math.max(...opts.map(o => o.cross));
      const top = opts.filter(o => o.cross === best);
      const pick = rnd() < 0.6 ? top[Math.floor(rnd() * top.length)] : opts[Math.floor(rnd() * opts.length)];
      put(w, pick.row, pick.col, pick.dir);
      crossTotal += pick.cross;
    }
  }
  return { grid, placed, crossTotal };
}

export type GenOptions = { category: CategoryId | "all"; level: Level; seed: number; id?: string; title?: string; number?: number };

export function generatePuzzle(opts: GenOptions): Puzzle {
  const { category, level, seed } = opts;
  const rnd = mulberry32(seed);
  const cfg = LEVEL_CFG[level];
  const pool = category === "all" ? bank : bank.filter(b => b.cat === category);

  let best: ReturnType<typeof build> | null = null;
  for (let attempt = 0; attempt < 40; attempt++) {
    const res = build(rnd, pool, cfg);
    if (!best || res.placed.length > best.placed.length ||
        (res.placed.length === best.placed.length && res.crossTotal > best.crossTotal)) best = res;
    if (best.placed.length >= cfg.target) break;
  }
  const { grid: full, placed } = best!;

  // обрезаем пустые поля
  let minR = full.length, maxR = 0, minC = full.length, maxC = 0;
  full.forEach((row, r) => row.forEach((ch, c) => {
    if (ch) { minR = Math.min(minR, r); maxR = Math.max(maxR, r); minC = Math.min(minC, c); maxC = Math.max(maxC, c); }
  }));
  const rows = maxR - minR + 1;
  const cols = maxC - minC + 1;
  const grid = Array.from({ length: rows }, (_, r) => Array.from({ length: cols }, (_, c) => full[r + minR][c + minC]));

  // нумерация по порядку начала слов
  const starts = new Map<string, number>();
  const startKeys = Array.from(new Set(placed.map(p => `${p.row - minR}-${p.col - minC}`)))
    .map(k => k.split("-").map(Number) as [number, number])
    .sort((x, y) => x[0] - y[0] || x[1] - y[1]);
  startKeys.forEach(([r, c], i) => starts.set(`${r}-${c}`, i + 1));
  const numbers: Record<string, number> = {};
  starts.forEach((n, k) => { numbers[k] = n; });

  const words: PWord[] = placed.map(p => {
    const row = p.row - minR;
    const col = p.col - minC;
    const cells: [number, number][] = Array.from({ length: p.a.length }, (_, i) =>
      p.dir === "across" ? [row, col + i] : [row + i, col]);
    return {
      number: starts.get(`${row}-${col}`)!,
      direction: p.dir,
      clue: p.clue,
      answer: p.a,
      hint: `Слово из ${p.a.length} букв, начинается на «${p.a[0]}».`,
      cells,
    };
  }).sort((x, y) => x.number - y.number || (x.direction === "across" ? -1 : 1));

  return {
    id: opts.id ?? `r-${category}-${levels.indexOf(level)}-${seed}`,
    title: opts.title ?? (category === "all" ? "Кроссворд-микс" : `Кроссворд: ${getCategoryName(category)}`),
    description: `${words.length} слов · сетка ${cols}×${rows}`,
    category,
    level,
    number: opts.number,
    rows,
    cols,
    grid,
    numbers,
    words,
  };
}

export function dailyPuzzle(dateKey: string): Puzzle {
  return generatePuzzle({
    category: "all",
    level: "Средний",
    seed: hashString("daily-" + dateKey),
    id: `daily-${dateKey}`,
    title: "Кроссворд дня",
  });
}

